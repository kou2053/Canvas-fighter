// ============================================================
//  1. 操作と入力の特別ルール   (script.js upd / keydown)
// ============================================================
//  ← →=移動  ↓=しゃがみ  ↑=上方向入力  Z=攻撃  A=必殺  X=シールド(押しっぱなし)
//  Space または C=ジャンプ  G=投げ  S=本体の必殺(押しながら A。メイ＆ロロだけ)  Esc=メニューへ戻る      (↑は初期のキー配置。メニューの「設定」で変えられる)
//
//  【設定】(メニュー → 設定 / script.js の「設定(キー配置など)」)
//   ・キー配置: 左・右・上・下・攻撃・必殺・シールド・ジャンプ・投げ・空中受け流し・本体の必殺 に、それぞれメインとサブの2つまでキーを割り当てられる。
//       ほかの操作で使っているキーを割り当てると、その操作と入れ替わる。Esc は割り当てられない(メニューに戻るキー)。
//       メニューの操作(↑↓←→ / Enter / Esc)はキー配置に関係なく固定。
//   ・簡単コマンド: ON にするとコマンドの途中の斜めを省略できる(3章)。
//   ・ヒット時の画面の揺れ / 対戦中の操作説明(画面下の表示): ON/OFF。
//   ・画質: 低(軽い) / 中 / 高(初期値) / 最高(重い)。←→ か Enter で切り替え。絵の細かさ(canvas の画素数)が変わるだけで、ゲームの動きは同じ。
//       種類と倍率は script.js の QUALITY。重いときは低くする。
//   ・フレームレート: 30fps(軽い) / 60fps(初期値)。変わるのは「画面を描く回数」だけ。ゲームの処理はいつも 1秒に60回(1F=1/60秒)で、
//       技のF数・当たり判定・CPU の動きはどちらでも同じ。種類は script.js の FPS_LIST。
//
//  【オンライン対戦に向けた決まり】(同じ入力なら、どの端末でも同じ結果になるようにしてある)
//   ・ゲームの進み方は「入力」と「upd の回数」だけで決まる。描く処理(draw)はゲームの状態を変えない。
//       見た目の姿勢(p.pose)・腰の高さ(p.hy)・武器を持つ腕の角度(p.wpArm)は食らい判定にも使うので、
//       draw ではなく upd の最初(drawing.js の stepPose)で1Fごとに進める。
//   ・乱数: upd の中の R() は種から決まる乱数(rngSeed(n) で種を決める)、draw の中の R() は Math.random(見た目だけ)。
//       オンラインでは両方の画面で同じ rngSeed をしてから試合を始める。
//   ・オンライン: 2人分の入力がそろっていないフレームは upd を何もしない(fr・姿勢 stepPose も進めない)。キャラの状態を変える物は必ずこの後に書く
//   ・新しい処理を足すときも、ゲームの状態を変える物は upd の中に、見た目だけの物は draw の中に書く。
//   ・設定はブラウザに保存される(save.keys / save.cfg)。「初期値に戻す」で元に戻る。
//
//  ・ダッシュ = ← か → を 14F 以内に2回押す(ダブルタップ)。空中でしゃがみ(下)を2回 か 空中受け流しのキー(初期設定 X) = 空中受け流し(10-2章)。
//      向いている方向と逆に2回押すと「バックダッシュ」(p.bd = true)。
//  ・Z / A / Space / C / G は「押した瞬間」だけ反応(押しっぱなしでは連打にならない)。
//      X(シールド)と方向キーは「押している間」反応。
//  ・コマンド技(3章)は、方向キーを順に入れてからボタン。成立していれば下の普通の技より優先。
//  ・攻撃の種類は押した瞬間の方向キーで決まる (pick)
//      地上:  Z=n  ↓Z=d  ↑Z=u  前Z=f  後ろZ=b  (走り中・ダッシュ中・速く動いている時の前Z=da)
//      地上:  A=s  前A=sf  後ろA=sb  ↑A=su  ↓A=sd(下必殺)
//        (後ろ = 相手と反対の方向。b / sb / sd が無いキャラは Z / A の技になる。↑と↓を同時に押すと ↑A)
//      空中:  Z/A=an  前=af  ↑=au  ↓=ad   (空中では A も空中技になる)
//  ・待機中で地上にいる時だけ、自動で相手の方を向く。攻撃中・空中では向きは変わらない。


// ============================================================
//  2. 移動   (script.js step)
// ============================================================
//  【歩き・走り】
//   ・同じ方向に 15F 以上押し続けると「走り」になり、速さ ×1.6(足元にほこり)。
//   ・相手と逆向き(後ろ)に歩くと速さ ×0.7。
//   ・↓を押している(しゃがみ)間は地上で移動しない。
//   ・ゆっくり歩き: 地上で ↓ と ← か → を同時に押す(斜め下)と、しゃがまずにゆっくり歩く(歩きの速さ × 0.4。後ろ向きはさらに ×0.7)。
//       このときはしゃがみ扱いではない(食らい判定は立ちのまま・しゃがみ受け流しは出ない)。走りにはならない。
//       移動ロック中(3章)は動けないので、今までどおりしゃがみになる。速さの倍率は script.js の SLOW_WALK、
//       キャラごとに stats の slowWalk で変えられる。斜め下+Z は今までどおり ↓Z(コマンドの ↘ もそのまま入る)。
//   ・地上の加速・減速の速さはステージの acc で決まる(氷原はとても滑る)。
//   ・空中では横移動がゆるやか(毎F 6% ずつ目標の速さに近づく)。
//   ・2人が近すぎる(横 30px 未満・両者地上)と、毎F 1.5px ずつ押し合って離れる(掴み中は除く)。
//
//  【ダッシュ】
//   ・14F で終わる。速さ = dashSpeed(既定 9) × (1 − 経過F/16)、最低 20%。だんだん減速。
//   ・ダッシュ開始から 7F 目以降に Z / A を押すと、そのまま攻撃に移れる(前Z ならダッシュ攻撃 da)。
//   ・バックダッシュの最初の 8F(t < 8)、前ダッシュ(前回避)の最初の 5F(t < 5)は無敵。攻撃も飛び道具も投げも当たらない。
//       F数は script.js の DASH_INVULN。トレーニングでは無敵の間、食らい判定が薄く表示される。
//   ・地上でしか出せない。moveLock 中(→3章)は出せない。
//
//  【ジャンプ】
//   ・jumpStartup(ジャンプ前隙)が 1F 以上あると、押してからそのF数しゃがみ込んでから跳ぶ。
//       跳んだ瞬間のフレームは地上の行動を受け付けない(ジャンプと同時押しの暴発防止)。
//   ・空中ジャンプ: airJumps 回(省略時 1回)。2段目以降の高さは通常の 85%。
//   ・moveLock 中はジャンプできない。
//   ・重力 = ステージの重力 × gravityMul。
//
//  【着地隙】
//   ・通常ジャンプで着地 → landLag F(省略時 3F)動けない。
//   ・空中技を出したまま着地 → その技の landLag(省略時 airLandLag、さらに省略時 9F)。
//       空中技でない技(地上技)を出したまま着地 → その技に landLag がなければ着地隙なし。
//   ・着地した瞬間も 1F に数える(設定値 = 動けない合計フレーム数)。
//   ・着地すると空中ジャンプの回数が戻る。


// ============================================================
//  3. 攻撃   (script.js step の atk / begin / pick)
// ============================================================
//  【技の役割】 1つの仕事に1つのスロット。新しい技を作るときも、この役割からはみ出さないようにする
//   スロット      役割                       使ってほしい場面                             性能の目安
//   n   (Z)       最速の小技・コンボ始動      密着で相手が動いた瞬間、コンボの1発目          発生3〜7F。地上の通常技でいちばん速い
//   d   (↓Z)      足元を狙う小技・コンボ2段目  足を刈ってコンボへ、受け流しの後の反撃          発生5〜10F。低い判定(足に当たり硬直×1.3)。多くは下段(10-1章)
//   f   (→Z)      いちばん長い差し込み         間合い管理、相手の技の先端を刺す               通常技でいちばんリーチが長い。空振りの隙は大きめ
//   b   (←Z)      下がりながら置く技           相手のダッシュ・突進を止める、詰められたとき    後ろへ下がる(launch x がマイナス)。威力は低め
//   u   (↑Z)      地上の対空・浮かせ           跳んできた相手を落とす、コンボで浮かせる        上に広い判定。浮かせる
//   da  (ダッシュZ) 一気に詰める               遠くから攻め込む、飛び道具を撃った相手の隙      前進する。ダッシュ中にしか出ない
//   an  (空中Z)    空中の最速技                空中の当て合い、空中コンボのつなぎ             発生が速く持続が長い
//   af  (空中→Z)   跳び込みの主力              ジャンプから地上を攻める                       斜め下前に強い
//   au  (空中↑Z)   空中から上                  空中の相手を追う、浮かせ直し                   上に広い
//   ad  (空中↓Z)   真下へ急降下                相手の真上から、着地のタイミングをずらす        当てると強いが着地隙が大きい
//   s   (A)       飛び道具                    遠距離戦、相手を跳ばせる                       撃つ隙は大きめ
//   sf  (→A)      ダメージ源・コンボの締め     コンボの最後、確定反撃                          威力最大級。ガードされたら反撃される隙
//   sb  (←A)      守りの必殺                  画面端から逃げる、攻められているとき           安全性重視。キャラの個性が出る枠
//   su  (↑A)      切り返し(昇竜)              攻められて困ったとき、コンボの最後             発生が最速クラス。空振りの隙は最大
//   sd  (↓A)      地上を広く払う・置く技        着地狩り、前後どちらにいても当てたいとき        判定が広い・発生遅め
//   投げ(G)        シールド崩し                シールドで固まる相手
//   コマンド技     キャラの個性                 —                                            上のスロットに無い性質だけにする
//
//  ・startup F のあと、active F の間だけ当たり判定が出る。そのあと recovery F の後隙。
//  ・1つの技は1回しか当たらない(当たったら残りの持続は空振り扱い)。
//  【多段技】 技に hits を書くと、その回数まで当たる(例: ツキハの月蝕の檻 hits: 6)。
//   ・2回目からは、前に当たってから hitInterval F(省略時 active ÷ hits)たってから当たる。ガードされても回数に数える。
//   ・damage・hitstun・吹っ飛び・hitStop は1回ごとの値。1回ごとにヒット数が増え、コンボ補正もかかる。
//   ・「同じ技の繰り返し」(6章)には、1つの技で1回だけ数える(多段技の2発目以降で空中の硬直が切れるようにはならない)。
//   ・最初の1発が当たった時点でキャンセルできる。
//  ・launch={x,y}: 発生した瞬間(t = startup)に自分に速度を加える(突進・飛び上がり)。
//  ・bounce={x,y}: 当たる・ガードされると、自分がこの速さで跳ね返る(シノの空中二段蹴り)。
//  ・float=n: 空中で出したとき、技の出始め〜持続の間は落ちる速さが n 以下になる(ツキハの空中技はふわっと止まる)。
//  ・通常技にも projectile を書くと、発生の瞬間に弾を撃つ(シノの散り苦無・ツキハの闇の雫)。
//      moveLock 中(技の後隙のあと)に出した技でも launch は効く(歩き・ダッシュ・ジャンプはできないが、動く技は動く)。
//  ・技が最後まで終わると moveLock = 後隙の半分(切り上げ)。この間は
//      歩き・ダッシュ・ジャンプができない(攻撃・シールド・投げは可能)。
//
//  【キャンセル】
//   ・技が当たったあと(発生後)に Z / A を押すと、より「ランク」の高い技に繋げられる。
//       ランク RK:  n=0 / d・an=1 / f・b・u・au・af・ad・da=2 / s=4 / sf・sb・sd=5 / su=6
//       今の技よりランクが高い技にしかキャンセルできない(同ランクや下には繋がらない)。
//   ・例) n → d → f → s → sf → su の順は全部つながる。f → u や f → b は同ランクなのでつながらない。
//   ・キャンセルできるのは「当たったとき」だけ。シールドでガードされた・しゃがみで受け流された技からはキャンセルできない。
//       → 当たったのを見てからキャンセルを入れる(ヒット確認)。当たりは止まりが長く(11〜22F)、ガードは短い(4F)ので、
//         止まりの長さでも見分けられる。ヒットストップ中に押したボタンは先行入力として残る(4章)。
//
//  【必殺 s】 発生した瞬間に飛び道具を撃つ(13章)。
//
//  【下必殺 sd】 地上で ↓ を押しながら A。キャンセルのランクは 5(sf・sb と同じ)。
//   ・コマンド技(↓↓+A など)が成立していればそちらが優先。sd を書いていないキャラは ↓+A で普通の必殺 s が出る。
//           技名              内容
//   ライキ   バーニングスイープ  炎の足払い(浮かす)
//   ガルド   アースクエイク     前後に広い衝撃波
//   シノ     撒菱              足元にまきびしを置く(持続が長い置き技)
//   ゴーレム 大地割り          とても広く重い衝撃波(発生は遅い)
//   バーサク 血溜まり落とし     足元から血の波が広がる踏みつけ
//   ツキハ   奈落の門          前後に広い闇の輪と紫の炎(発生は遅い)
//   リナ     アンプクラッシュ   足元を前後に広く走る電撃(浮かす)
//   ルリ     大津波             地面を踏みつけ、前へ大きな水の衝撃波(浮かす)
//   アサカ   天光の柱           離れた所へ空から光の柱が落ち、相手を地面へたたきつける(バウンド。発生は遅い)
//   メイ     綿爆弾             ロロがその場で綿をふくらませ、36F 後に自爆してまわりを大きく吹き飛ばす(ロロの耐久が 10 減る。0 ならクラッシュ)
//   ※ 足元だけを払う sd は下段(しゃがみ受け流しできない。10-1章)
//
//  【コマンド投げ】 コマンド入力でつかんで投げる技(character.js の技の grab。書き方は character.js 冒頭の【コマンド投げ】)。
//   ・ガード(シールド)・ジャストガード・しゃがみ受け流しでは防げない。空中の相手・無敵中の相手はつかめない。ふつうの投げと相殺しない。
//   ・空振りすると recovery の間動けない(つかめる範囲はふつうの打撃よりせまいので、近づいて狙う)。
//           技名                  入力       内容
//   ガルド   ジャイアントスイング   ↓↙←+Z   足をつかんで2回半ふり回し、遠くへ放る(画面の端へ運ぶ)。威力18
//   ガルド   パワーボム             ↓↘→+Z   頭上高く持ち上げて前の地面へたたきつける。はね上がるので追い打ちできる。威力22
//   ゴーレム 岩締め                 ↓↘→+Z   出は遅いが遠くからつかみ、3回しめつけてから放る。合計23
//   シノ     飯綱落とし             →↓↘+Z   一気に踏み込んでつかみ、高く跳んで頭から落とす。発生4F・範囲はせまい。威力15
//   バーサク 血吸い                 ↓↙←+Z   3回かみついて吸血し、後ろへ振り捨てる(立ち位置が入れ替わる)。合計19
//   ルリ     水牢                   ↓↘→+Z   水の玉に閉じこめて持ち上げ、水柱で真上へ打ち上げる。威力は小さいが高く浮くので追撃できる
//
//  【上必殺 su】 地上で ↑ を押しながら A。キャンセルのランクは 6。キャラごとに「切り返し・対空」のやり方がまったく違う。
//           技名                  内容
//   ライキ   ライジングフレア       出始め6F無敵で昇る、昔ながらの昇り技(基準)
//   ガルド   アイアンハンマー       跳ばずにアーマー2回で受け止め、頭上から地面へたたき落とす(叩きつけ)
//   シノ     昇り燕・連            蹴りを重ねながら真上へ昇る5段。1発は軽いが相手を上へ運び続ける(無敵なし)
//   ゴーレム 大地の怒り            跳ばずに、まわり全体から岩が噴き上がる。アーマー1回(前後どちらの飛び込みも落とす。発生は遅い)
//   バーサク 血昇拳                無敵なし・アーマー1回。体力5を払って出し、当てると半分吸う
//   ツキハ   ルナライズ            斜め上へゆっくり昇って止まる闇の月を置く(置き対空。近くでは間に合わない)
//   リナ     ライトニングリフ      ギターを大きく振り上げて跳ぶ。前の上まで広く届く。ボルテージ50以上で高く強く
//   ルリ     水爆昇                水をまとって昇る4段。相手をそばに浮かせたまま空中コンボへ運ぶ
//   アサカ   サンライズ・ブルーム  無敵なし。斜め前へ飛び出して追いかける対空(後隙は短め)
//   メイ     飛びかかり            メイは跳ばない。ロロが斜め前へ大きく跳び、落ちながら振り下ろす(対空・飛び道具を跳び越す・しゃがみ受け流しできない)
//
//  【コマンド技】 (書き方は character.js 冒頭の【コマンド技】/ 判定は script.js の「コマンド技」)
//   ・方向キーを順番に入れてからボタン。→ は前(相手の方)、← は後ろ。最初の方向からボタンまで 18F 以内(技ごとに変更可)。
//   ・途中に余計な方向が混ざっても成立する。斜めも入れる必要がある(設定画面の「簡単コマンド」を ON にすると途中の斜めを省略できる)。
//   ・同じ方向を2回(↓↓)は、間で一度離す。ヒットストップ中も入力は記録され、その間は受付時間を数えない。
//   ・コマンドが成立していれば、同じボタンの普通の技より優先(長いコマンドほど優先)。
//   ・キャンセルのランクは技ごとの rank(省略時 3)。下の表の rank 5 は sf と同じ。
//   ・CPU もコマンド技を使う(入力にかかるF数も計算に入れてコンボ・反撃に使う)。
//   ・トレーニングでは、コマンド技が出ると技名が表示される。
//
//           c1                                  c2                                  その他
//   ライキ   烈風跳脚 ↓↘→+Z(跳んで飛び道具を越える蹴り)   流星炎脚 空中で →↓↘+A(斜め下へ急降下・rank5)
//   ガルド   頭突き ↓↓+Z(密着の確定反撃・高威力)        フライングボディプレス ←→+A(跳んで押しつぶす)
//   シノ     鎖分銅 ↓↘→+A(遠くの相手を引き寄せる)      影縫い ↓↙←+Z(滑り込み足払い)          c3 空中苦無 空中で ↓↘→+A
//   ゴーレム 岩柱 ↓↓+A(離れた所に岩の柱・対空)          岩砕拳 ←→+Z(とても遅いが威力30の一撃)
//   バーサク 血の咆哮 ↓↘→+Z(まわりを大きく吹き飛ばす)   狂跳斬 ↓↓+A(前へ跳んで爪で斬る・rank5)
//   ツキハ   夢幻蝶 空中で ↓↘→+Z(黒い蝶の羽で前へ滑空する・rank0)  月蝕の檻 ↓↙←+A(前に40F残る闇の檻・6段)
//   リナ     ギターソロ ↓↘→+Z(5段の連撃・ボルテージ100で3段の強いライブ版)  ステージダイブ 空中で →↓↘+A(斜め下へ急降下・rank7)
//   ルリ     曲水弾 ↓↘→+A(上へ撃ち出し、相手の方へ曲がる水弾)  逆流 ↓↙←+A(カウンター。構え中に打撃を受けると打ち返し、飛び道具は跳ね返す。投げに負ける)
//   アサカ   天降花 空中で ↓↘→+Z(光の羽を広げて斜め下へ突撃・rank5)  フルブルーム ↓↙←+A(まわりに大輪の花が一瞬で咲き、大きく突き放す)
//   メイ     呪いの釘 ↓↘→+Z(出した瞬間の相手の位置に呪いの印。32F後に巨大な釘が落ちる。動けば避けられる)  糸繰り ↓↙←+A(ロロから糸を飛ばし、当てた相手をロロの方へ引き寄せる)


// ============================================================
//  4. ヒット時の計算   (script.js applyHit)
// ============================================================
//  ダメージ = 技の damage × 攻撃側 damageMul × 部位 dmg × (受け流しなら cg.dmg) × コンボ補正
//            (四捨五入、最低 1)
//  硬直    = 技の hitstun × 部位 stun × (受け流しなら cg.stun) × コンボ補正 × 同技補正
//  吹っ飛び横 = 技の knockX × 部位 knock × (受け流し knock) × 受け側 knockbackTaken
//  吹っ飛び縦 = 技の knockY × 部位 knock × 受け側 knockbackTaken  (受け流しなら 0 = 浮かない)
//  ヒットストップ = min(22, 9 + ダメージ×0.6) + 部位 stop     (受け流しなら cg.stop = 5F)
//      例) ダメージ4 → 11F / 9 → 14F / 15 → 18F / 21以上 → 22F(頭に当たると +6F)
//      技ごとに moves の hitStop で上書きできる。式の数値は character.js の HIT_STOP
//    ・ヒットストップ中は両者・飛び道具・ステージギミックすべてが止まる(揺れ物も止まる)。
//    ・先行入力: ヒットストップ中に押した Z / A / ジャンプ / 投げ は覚えておき、止まりが解けたフレームに出る。
//        方向キーはその時に押している向きを使う(例: 止まっている間に Z を押し、↓を押したままにすると ↓Z でキャンセル)。
//  ・ヒットした相手はそれまでの技が中断される。


// ============================================================
//  5. 当たり部位   (character.js HIT_ZONES / drawing.js fighterHitParts)
// ============================================================
//  ・食らい判定は見た目と同じ形(頭=円、腕・脚=骨に沿った太さのある線、手・足先=円、胴=線)。
//    手足の向き(奥・手前の縮み)も判定に反映される。攻撃の判定は四角形(box)。
//  ・複数の部位に触れたときは、頭 → 腕 → 脚 → 胴 の順に先に見つかった部位になる。
//
//          dmg   stun  knock  stop   表示
//   頭    ×1.5  ×1    ×1.15  +6F   HEAD!
//   胴    ×1    ×1    ×1     0
//   腕    ×1    ×1    ×1     0     (胴と同じ扱い)
//   脚    ×0.6  ×1.3  ×0.9   0     FEET   (ダメージは低いが硬直が長い)
//
//  ・キャラごとに zones で上書きできる(例: ガルドは頭 ×1.25 の石頭)。
//  ・しゃがみ中(またはしゃがみで受けた硬直中)は身長が 100 → 44 になり、食らい判定が低くなる。
//  ・受け流し(しゃがみ・空中)が成功したときは、頭に当たっても頭の補正はかからない(胴と同じ。10章)。


// ============================================================
//  6. コンボ補正   (script.js applyHit)
// ============================================================
//  ・相手が硬直中(hit)に当てると「コンボ」としてヒット数 cb が増える。
//      硬直が切れて待機に戻るとリセット。画面に「n HIT!」(2HIT以上、70F 表示)。
//  ・ヒット数による補正(2ヒット目以降、1ヒットごとに)
//      ダメージ ×(1 − 0.07×(cb−1))  最低 ×0.5
//      硬直     ×(1 − 0.07×(cb−1))  最低 ×0.55
//  ・同じ技の繰り返し補正(1コンボ中に同じ技スロットが当たった回数で)
//      硬直 ×(1 − 0.15×(回数−1))  最低 ×0.8
//        1回目 ×1 / 2回目 ×0.85 / 3回目以降 ×0.8
//  ・さらに同じ技を2回以上受けると、空中の硬直が「空中でも切れる」ようになる(7章)。
//  ・投げもコンボに入る(硬直中の相手を掴んだ場合のみ)。投げの硬直はコンボ補正を受けない。


// ============================================================
//  7. 空中での硬直と着地硬直   (script.js step / 着地処理)
// ============================================================
//  ・空中で攻撃を受けると、着地するまで硬直が減らない(空中では動けない)。
//  ・着地すると、その技に設定された硬直(補正後の値 hitStunFull)が最初からもう一度始まる。
//      つまり「空中で何Fいても、着地してから技の硬直分しっかり動けない」。
//      トレーニングでは「着地硬直 nF」と表示される。
//  ・例外: そのコンボで同じ技を2回以上受けている(airStunCanExpire)と、
//      空中でも硬直が減って切れる。着地したときは残り硬直と 16F の長いほう。
//      → 同じ技で空中に永久に拾い続けるのを防ぐための仕様。
//  ・硬直のまま着地すると横の勢いは 30% に減る。


// ============================================================
//  8. シールド・ガードブレイク   (script.js applyHit / step)
// ============================================================
//  ・X 押しっぱなしでシールド。押したフレームを 0F目として:
//      0〜3F目(4F)= ジャストガード(9章) / 4〜8F目(5F)= ガード判定なし(攻撃を受けるとふつうに当たる) / 9F目から = ふつうのガード
//      数値は script.js の JUST_GUARD(window=ジャストガードのF数 / gap=ガード判定なしのF数)。
//  ・離すと 10F の解除モーション(sdown)。押してから 6F 目までは離しても解除されない。シールドは地上でしか出せない。
//  ・ガードから直接出せる行動(ふつうのガードが張られてから=9F目から。解除の 10F を待たずに出る):
//      最初の 9F(ジャストガードの受付 4F + ガード判定なし 5F)は硬直で出せない(押しても出ない)。ジャストガード成功のあとはすぐ出せる。
//      投げ(G。方向で投げ分けもそのまま) / 下必殺(↓A = sd。sd が無いキャラは出ない) / ジャンプ(ジャンプ前隙はふつうどおり。移動ロック中は不可)
//      ほかの技(Z・A など)はシールドを離してから。コマンド技もガードからは出ない。
//  ・シールド量: shield(既定 60)。張っている間は毎F 0.05 減る。
//      張っていない間は毎F 0.12 回復。
//  ・ガードすると シールド −= max(3, 技のダメージ) × 1.6。体力は減らない。
//      守った側は knockX×0.4 で押され、攻撃側は 2.5 で後ろに押し返される。
//      ヒットストップ = 技の guardHitStop(省略時 4F。飛び道具も 4F)。当たり(11〜22F)より短い。
//      ガードされた側は、その技からキャンセルできない(3章)。
//  ・シールドが 0 以下 → ガードブレイク。100F 動けない(シールドは満タンに戻る)。
//  ・空中からの攻撃も地上のシールドで守れる。


// ============================================================
//  9. ジャストガード   (script.js applyHit)
// ============================================================
//  ・シールドを押した瞬間から 4F(0〜3F目。キャラの justGuardFrames で変えられる)の間に攻撃を受けると成功。
//      その後の 5F はガード判定がない(早く押しすぎると当たる)。ふつうのガードは 9F目から。
//  ・成功すると:
//      守った側 → シールドを離せばすぐ動ける(シールド解除の 10F もない) / シールド +12 回復 / 青いリングのエフェクト(24F)
//                 シールドを押し続けていると、ガード判定なしの 5F が無くなり、そのままふつうのガードになる(続く攻撃をガードできる)
//      攻撃側   → 技が中断され 30F の硬直。後ろに 4 押し返される
//      ヒットストップ 20F
//  ・空中の攻撃をジャストガードされた場合、攻撃側は着地するまで動けず、
//      着地してから 30F の硬直が始まる(空中で時間が過ぎても減らない)。
//  ・飛び道具をジャストガードすると、跳ね返る(→13章)。


// ============================================================
//  10. しゃがみ受け流し   (script.js applyHit / character.js CROUCH_PARRY)
// ============================================================
//  ・地上で ↓ を押して待機(しゃがみ)しているときに攻撃を受けると自動で発動。
//      シールドのように構える必要はないが、体力は減る。
//  ・既定の倍率:  ダメージ ×0.3 / 硬直 ×0.4 / 吹っ飛び ×0.25 / ヒットストップ 5F / 浮かない
//      「受け流し ×0.5」と表示。硬直中もしゃがみ姿勢のまま(判定も低いまま)。
//  ・キャラごとに crouchParry で上書き(ガルド dmg 0.4・knock 0.18 / ゴーレム dmg 0.25・stun 0.3・knock 0.12)。
//  ・コンボ補正・部位補正とも重なってかかる。ただし頭に当たったときの補正(ダメージ ×1.5・吹っ飛び・ヒットストップ +6F・HEAD! の表示)はかからず、
//      胴に当たったのと同じ扱いになる(頭の判定は残る。空中受け流しも同じ)。脚・腕の補正はそのままかかる。
//  ・受け流された側は、その技の後隙が 12F 伸びる(CROUCH_PARRY.lag。空中技なら着地隙が伸びる)。戻りの動きもその分ゆっくりになる。
//      lag は受け流した側のキャラの値を使う(crouchParry で上書き可)。トレーニングでは「後隙+12F」と表示。CPU もこの隙に反撃してくる。
//  ・受け流された側は、その技からキャンセルできない(技が最後まで終わるまで次の技を出せない)。
//      飛び道具は対象外(撃った本人はそもそもキャンセルできない)。CPU も受け流されたらキャンセルを狙わない。
//  ・しゃがみから攻撃の補正: しゃがんでいた次のフレームで技を出すと、その技のダメージが ×0.6(script.js CROUCH_ATTACK)。
//      ↓ を押したまま Z(ボディフックなど)も、↓ を離して出した技も対象。立った状態から ↓ と Z を同時に押した技は対象外。
//      多段技は全段、飛び道具はその技で撃った弾に乗る。キャンセルでつないだ次の技には乗らない。他の補正とも重なってかかる。
//      トレーニングの行動履歴で技名のあとに「×0.6」と出る。
//  ・下段攻撃(10-1)には発動しない(しゃがんでいても、ふつうに当たる)。


// ------------------------------------------------------------
//  10-1. 下段攻撃   (script.js LOW_ATTACK / isLowMove / applyHit)
// ------------------------------------------------------------
//  ・下段攻撃は、しゃがみ受け流しができない攻撃。しゃがんでいる相手に当たると、ふつうのヒットになる
//      (ダメージ・硬直・吹っ飛びは軽減されない / 攻撃側の後隙は伸びない / ヒットを見てキャンセルできる)。
//      → しゃがんで待つ相手には下段、立っている相手には…という読み合いになる。シールドではふつうにガードできる。
//  ・どの技が下段か:
//      技に low: true / low: false を書くと、その通り(character.js 冒頭の説明)。
//      書いていない技は自動: 地上で出す技で、当たり判定の下の端が足元から 12px 以内 かつ 上の端が足元から 50px 以内(足元だけを払う技)。
//      上から下まで届く大きな判定の技(超必殺技など)は下段にならない。数値は script.js の LOW_ATTACK(reach / top)。
//  ・空中技(an / af / au / ad / 空中のコマンド技)・飛び道具・空中にいるときに当てた攻撃は下段にならない。
//  ・空中受け流し(10-2)には関係しない(下段でも空中受け流しはできる)。
//  ・今の下段(自動の判定):
//      ライキ ボディフック・バーニングスイープ / ガルド ローキック・アースクエイク / シノ しゃがみ突き・影滑り・撒菱・影縫い /
//      ゴーレム 地響き・大地割り / バーサク 足狩り・血溜まり落とし / ツキハ 影の棘・奈落の門 / リナ ローカット・ニースライド・アンプクラッシュ / アサカ 芽吹き /
//      メイ ロロの呪いの衝撃波(↓Z)・影縫い(S+↓A。ロロの大針の追撃も)(ロロの技は low: true のものが下段)
//  ・CPU も、しゃがんでいる相手に下段を当てるとふつうに当たる前提でコンボを考える。
//  ・メニューの「キャラクター」で技を選ぶと、下段の技には「下段」と出る(24章)。


// ------------------------------------------------------------
//  10-2. 空中受け流し   (script.js AIR_PARRY / applyHit / step)
// ------------------------------------------------------------
//  ・空中で動ける状態(ジャンプ中・落下中)のときに、しゃがみ(設定の「下(しゃがみ)」のキー)を2回(14F 以内)押すか、
//    空中受け流しのキー(設定で変えられる。初期設定は X)を押すと発動。地上では出ない(地上の X はふつうにシールド)。
//    空中受け流しのキーは、ほかの操作(シールドなど)と同じキーにしてもよい。しゃがみ2回はいつでも使える
//  ・出てから 2F 後の 8F 間(3〜10F目)が受付。この間に攻撃(飛び道具も)を受けると成功。
//  ・成功すると、地上のしゃがみ受け流し(10章)と同じ扱いになる(倍率は CROUCH_PARRY / キャラの crouchParry):
//      受け流した側 → ダメージ ×0.3 / 吹っ飛び ×0.25 / 浮かない / ヒットストップ 5F。「空中受け流し!」と表示
//                     硬直はなし(ヒットストップが解けたらすぐ動ける。コンボにも数えない)。飛び道具は消える
//      攻撃した側   → その技の後隙が 12F 伸びる(空中技なら着地隙が伸びる)・その技からキャンセルできない
//      → 伸びた後隙に反撃・コンボを入れられる
//  ・連続攻撃: 成功するとすぐふつうの空中の状態に戻るので、次の攻撃にもう一度 ↓↓ を合わせれば、また受け流せる
//      (受付は毎回 8F だけ。押しっぱなしや連打で受け続けることはできない)
//      ヒットストップ中・空中受け流し中に入れた ↓↓ は 12F 覚えておき、動けるようになったフレームに出る
//  ・失敗(受付の間に何も来なかった): 空中で 20F 動けない。さらに、着地するまでに地面に着くと着地硬直が 16F になる
//      (受付の途中で着地しても失敗扱い)。受付の前の 2F と失敗の隙の間に攻撃を受けると、ふつうに当たる。
//  ・数値は script.js の AIR_PARRY(startup / active / whiff / failLand / window)。成功したときの倍率はしゃがみ受け流しと共通。
//  ・上級CPU(Lv6〜10)も使う(16章)。トレーニングの「相手の行動」に「空中受け流し(攻撃に合わせる)」がある(跳んで、攻撃が受付の真ん中に来るように ↓↓)。


// ============================================================
//  11. 投げ   (script.js beginThrow / throwStep / releaseThrow)
// ============================================================
//  ・G で投げ。押した瞬間の方向で投げ分け: 前(入力なしも前) / 後 / ↑ / ↓。
//  ・地上でしか出せない。地上にいる相手しか掴めない。
//  ・掴める相手の状態: 待機・シールド中・シールド解除中・着地隙・ダッシュ中・攻撃中・
//      ガードブレイク中・硬直中・投げの掴みが出る前/空振りの隙。→ シールドは投げで崩せる。
//      ダッシュの無敵中(バックダッシュの最初の 8F・前ダッシュの最初の 5F)は掴めない。
//  ・以下は既定値(DEFAULT_THROW)。今は全キャラが character.js の throw で独自の値を持っている。
//  ・既定のフレーム: 発生 6F → 掴み判定 3F → 空振りなら +22F の隙
//      掴んだら 34F目で投げる / 全体 60F
//  ・掴んだ瞬間ヒットストップ 9F、「掴み!」表示。掴まれた側は投げ終わるまで動けない。
//  ・投げのダメージと硬直(既定)
//      前 10ダメ/26F  後 9ダメ/26F(相手を自分の後ろへ)  上 7ダメ/30F(高く浮かす)
//      下 11ダメ/30F(地面に叩きつけてバウンド)
//  ・後ろ投げは2人の立ち位置が入れかわる: 相手を自分の後ろ BACK_THROW_GAP(40)px の所へ置く。
//      画面端を背負っていて、後ろに置く場所が無いとき(壁際)は、相手を端(画面の端から 30px)に置き、
//      投げた側がその前(40px 前)へ移動する → 壁際でも必ず入れかわり、相手が端を背負う(重なったままにならない)。
//      数値は script.js の BACK_THROW_GAP(releaseThrow)。
//    ダメージには攻撃側 damageMul、吹っ飛びには受け側 knockbackTaken がかかる。
//    投げはコンボ補正・部位補正を受けない。ヒットストップ = min(24, 12 + ダメージ×0.7)。
//  ・硬直中の相手を掴むとコンボが続く(ヒット数+1)。2回以上投げると空中の硬直が切れるようになる。
//  ・投げ相殺: お互いの掴みがほぼ同時(THROW_CLASH.window = 2F 差まで)に出ると、どちらも掴めず
//      「投げ相殺!」になり、両者とも後ろへ弾かれて(速さ 8)、同じだけ(14F)動けない。ヒットストップ 8F。ダメージなし。
//      数値は character.js の THROW_CLASH。
//  ・相手の投げの掴みが出る前に自分の掴みが出れば、普通に掴める(先に出した投げが勝つ)。
//      投げを空振りした相手(空振りの隙の間)も掴める。
//  ・メイ＆ロロ: メイの投げがつかめなかったとき、ロロのそばに相手がいればロロがつかむ(15-1章)。メイの投げ・ロロの投げはどちらも4方向それぞれ別の動き


// ============================================================
