// ============================================================
// body  (drawing_character.js の CHARACTER_DRAWS[キャラ名].body)
// ============================================================
//
// 体の大きさ・服の色・形は、すべて drawing_character.js の body に書く。
// character.js の look に残るのは次だけ:
//   color   … 体の基本色(胴体・袖・マント・飛び道具など。スキンを買うとこの色が変わる)
//   skin    … 肌の色
//   smooth  … 動きの追従の速さ
//   dir     … 基本の向き
//   ※ 以前の character.js の look.body は廃止。書いてあっても読むが(コンソールに警告)、
//     drawing_character.js の body の値が優先される。
//
// 大きさはすべて px の数字で書く(倍率はない)。省略した項目は下の「省略時」の値になる。
//
// body: {
//   // ---- 大きさ (px) ----                        省略時
//   scale: 1,               // 全体の大きさ          1     (見た目・当たり判定の両方。ここだけは倍率)
//   headRadius: 13,         // 頭の半径              13
//   handRadius: 9,          // 手の半径              9
//   torsoLength: 36,        // 胴の長さ              36
//   torsoWidth: 22,         // 胴の太さ              22    (肩・腰の位置、当たり判定も連動)
//   upperArm: { length: 25, width: 11 },   // 上腕の長さ・太さ   25 / 11  (当たり判定も同じ)
//   lowerArm: { length: 24, width: 11 },   // 前腕の長さ・太さ   24 / 11  (袖などの設定も同じ { } の中に書く。下の「腕」)
//   thighLength: 21,        // 太ももの長さ          21    (腰の高さ・当たり判定も連動)
//   shinLength: 21,         // すねの長さ            21
//   legWidth: 13,           // 脚の太さ              13    (靴の大きさ・当たり判定も連動)
//   thighWidth: 15,         // 太ももの太さ          (省略時 legWidth。当たり判定も連動)
//   shinWidth: 11,          // すねの太さ            (省略時 legWidth。靴の大きさ・当たり判定も連動)
//     ※ 太ももとすねの太さが違うときは、ひざのまわりでゆるやかに太さが変わる(drawing.js の LIMB_BLEND で範囲を変えられる)
//
//   // ---- 色 ----
//   pantsColor: "#2a2a3a",  // ズボン(脚)の色        "#2a2a3a"
//   beltColor: "#fff",      // 腰のベルトの色        "#fff"   (ctx.Y.sh でも参照できる。シノの帯など)
//   buckleColor: "#fc3",    // バックルの色          "#fc3"
//   belt: false,            // ベルトを外す(バックルも消える)。beltColor: false でも同じ
//   buckleColor: false,     // バックルだけ外す(ベルトは残る)
//   sleeves: true,          // 上腕の色              true     true=look.color(袖あり) / false=肌の色(袖なし)
//   foreArmColor: "#f2c79c",// 前腕の色              肌の色   (手袋・長袖なら服の色にする)
//   handColor: "#fff",      // 手の色                肌の色
//   shoesColor: "#111",     // 靴の色                "#111"
//
//   // ---- 服 ----
//   top: "plain",           // 服(上)のテンプレート    "plain"  (下の「服(上)・ズボン(下)」を参照)
//   bottom: "pants",        // ズボン(下)のテンプレート "pants"
//
//   // ---- 形 ----
//   torsoType: "standard",  // 胴体テンプレート(形だけ。太さは torsoWidth)
//   torsoProfile, torsoBack,// 独自の胴体の形(TORSO_TEMPLATES と同じ書式。幅は torsoWidth に対する割合)
//   armType: "standard",    // 腕テンプレート (下の「腕」を参照)
//   elbowGuard: false,      // 肘当て (true / { color, r, spike })
//   armBand: "#c33",        // 腕輪の色
//   hand: "normal",         // 手の形 (normal=握りこぶし / block=四角い手)
//   handOutline: true,      // 手のライン追加 (握りこぶしの指の付け根の線)
//   limbShape: "human",     // 腕・脚の形 (human=人の形 / block=まっすぐな石・機械の形)  ※下の「腕・脚の形」
//   shoeLegCover: false,    // 靴が脛まで覆う
//   legPatch: false,        // ゴーレム風継ぎ目
//   armDecoration: false    // 特殊装飾
// }
//
// 廃止した項目 (書いてあっても同じ見た目になるように読み替えるが、コンソールに警告が出る):
//   limbWidth          → upperArm.width / lowerArm.width / legWidth(= limbWidth + 2)
//   armWidth (倍率)     → upperArm.width / lowerArm.width に掛けた値を書く
//   torsoBaseWidth     → torsoWidth (px)          ※ torsoWidth はもう倍率ではない
//   upperArmLength     → upperArm.length          foreArmLength → lowerArm.length
//   legLength (倍率)    → thighLength / shinLength に掛けた値を書く
//
// 以前の character.js の look.body との対応:
//   scale→scale   headR→headRadius   handR→handRadius   limbW→upperArm/lowerArm の width と legWidth(+2)
//   torso→torsoLength   torsoW→torsoWidth   upperArm→upperArm.length   foreArm→lowerArm.length
//   thigh→thighLength   shin→shinLength   pants→pantsColor   belt→beltColor
//   sleeves(1/0)→sleeves(true/false)   foreColor→foreArmColor   handColor→handColor   shoes→shoesColor
//
// torsoType:
//   standard
//   slim
//   broad
//   barrel
//   hourglass
//   blocky
//
// hand:
//   normal    握りこぶし(前腕の向きに握り、親指つき)
//   block     四角い手(ゴーレム向き)
//
// limbShape:
//   human     人の形(省略時)。肩・力こぶ・前腕・太もも・ふくらはぎのふくらみと、肘・ひざ・手首・足首のくびれ
//   block     まっすぐな太さ(ゴーレムなど石や機械の体)
//
// armDecoration:
//   false
//   "berserk"

// ------------------------------------------------------------
// 服(上)・ズボン(下)  (body.top / body.bottom)
// ------------------------------------------------------------
//
// キャラがいつも着ている服とズボンを、テンプレートの名前で選ぶ。省略すると plain / pants (以前と同じ見た目)。
//
//   top: "hoodie"                                          // 名前だけ
//   top: { type: "jacket", color: "#334", inner: "#fff" }   // 色なども変える
//   bottom: { type: "shorts", color: "#a63", hem: 0.6 }
//
//   ※ 見た目だけ(当たり判定は変わらない)
//   ※ 色を省略すると、上の服 = キャラの基本色(character.js の look.color。スキンを買うと変わる)
//                     ズボン   = body.pantsColor
//   ※ 色の代わりに次の名前も書ける: "skin"(肌の色) / "main"(キャラの基本色) / "top"(上の服の色) / "inner"(中の服の色)
//   ※ 上の服のテンプレートは袖も決める(Tシャツ=半袖、ジャケット=長袖 など)。
//     body.upperArm / body.lowerArm に書いた袖・色のほうが優先される
//   ※ 体の向き(正面・背面)に合わせて、前の開きやボタンは胸の真ん中へ、背中側ではフードなどが見える
//   ※ torsoUsesSkin: true のキャラは、top に関係なく胴体が肌の色になる(top: "none" と同じ)
//
// top (服・上):
//   plain    無地(標準)。胴の縫い目だけ                    color
//   none     服なし(上半身裸。上腕も肌)
//   tshirt   Tシャツ: 丸首・すそ・半袖                       color
//   tank     タンクトップ: U字の胸元・袖なし                 color
//   shirt    シャツ: 襟・前立て・ボタン・長袖                color / buttons(ボタンの数 4) / button(ボタンの色)
//   jacket   ジャケット: 前が開いて中の服が見える・襟・長袖   color / inner(中の服の色 "#eeeeee") / lapel(false で襟なし)
//   hoodie   パーカー: フード・ポケット・ひも・すその帯・長袖  color / strings(ひもの色。false で無し) / hood / pocket / band (false で無し)
//   gi       道着・着物: 打ち合わせの襟・広がり袖            color / trim(襟の色 "#ffffff")
//   vest     ベスト: シャツの上にベスト(袖はシャツ)          color(ベスト) / inner(シャツ "#eeeeee") / buttons(3) / button
//   armor    胸当て: 胸と背中に金属の板                      color(下の服) / plate(板の色 "#aab4c8") / rivet(鋲の色。false で無し)
//
// bottom (ズボン・下):
//   pants    長ズボン(標準)                                  color
//   shorts   半ズボン: ひざの上まで、すねは肌                color / hem(すその位置 0〜1。太ももの付け根=0、ひざ=1。省略 0.72)
//   jeans    ジーンズ: 縫い目・すその折り返し                color / stitch(糸の色 "#d9a64a"。false で無し) / cuff(false で折り返し無し)
//   cargo    カーゴパンツ: ももにポケット                    color
//   wide     袴・ワイドパンツ: すそが広がる                  color / flare(すその太さ 脚の何倍か 1.9) / hemLine(false で線無し)
//   baggy    だぼっとしたズボン: 太く、足首で絞る            color / thighAdd / shinAdd(太さの増減 px。4 / 3)
//   greaves  すね当て: すねに金属の板・ひざ当て              color / greave(板の色 "#9aa4b8")
//   socks    ハイソックス: 素足 + ひざ下までの靴下            sock(靴下の色 "#ffffff") / top(はき口の位置 0 ひざ〜1 足首。0.04) / trim(はき口の線の色)
//
//   テンプレートの項目は、どれも { } の中に書いて上書きできる(例: top: { type: "hoodie", pocket: false })
//
// 例) パーカーと半ズボン
//   body: { ..., top: { type: "hoodie", color: "#3a6" }, bottom: "shorts" }
//
// 例) 黒いジャケットに白いシャツ、袴
//   body: { ..., top: { type: "jacket", color: "#222", inner: "#fff" }, bottom: { type: "wide", color: "#334" } }

// ------------------------------------------------------------
// 腕 (上腕 / 下腕を別々に設定できる)
// ------------------------------------------------------------
//
// 腕の長さ・太さは body.upperArm / body.lowerArm の length / width (px) で決める。
// body.armType にテンプレート名を書くと、袖などの見た目と、太さ・長さの増減(px)がまとめて決まる。
// body.upperArm / body.lowerArm に書いた項目は、テンプレートより優先される。
// (sleeve / wrap / band の中身も、書いた項目だけが上書きされる)
//
// 何も書かなければ標準の腕になる。
//
// armType:
//   standard      標準
//   slender       細腕                          (太さ 上腕 -2px / 前腕 -3px)
//   muscular      筋肉質(上腕も前腕も太い)       (太さ 上腕 +4px / 前腕 +2px)
//   brawler       前腕が極太(殴り手)             (太さ 上腕 +3px / 前腕 +7px)
//   longArms      長い腕                        (長さ 上腕 +4px / 前腕 +5px)
//   shortArms     短い腕                        (長さ 上腕 -4px / 前腕 -4px)
//   gauntlet      篭手(前腕が太く金属の腕甲つき)  (太さ 前腕 +4px)
//   bracer        前腕に革の腕輪
//   longSleeve    長袖(上腕・前腕とも袖、袖口に縁)
//   shortSleeve   半袖(上腕の途中まで)
//   mageSleeve    広がり袖(前腕の袖口が広がる。魔法使い・巫女向き)  (太さ 前腕 -1px)
//   puffSleeve    ふくらみ袖(上腕が太く、前腕は袖口だけ)          (太さ 上腕 +5px)
//   bandaged      包帯ぐるぐる
//
// upperArm / lowerArm に書ける項目(すべて省略可):
//
// {
//   length: 25,       // 長さ(px)
//   width: 11,        // 太さ(px)
//                     //   ※当たり判定の腕の長さ・太さも同じ値
//   lengthAdd: 0,     // 長さの増減(px)。テンプレートが使う(length に足される)
//   widthAdd: 0,      // 太さの増減(px)。テンプレートが使う(width に足される)
//   color: "#a22",    // この部分の色(省略時は標準の腕の色)
//
//   sleeve: {         // 袖。false で無し
//     color: "#a22",  //   省略時はキャラの基本色
//     trim: "#fc3",   //   袖口の縁の色(省略時は袖を暗くした色)
//     cover: 1,       //   袖の長さ 0〜1 (根元=0、先端=1)
//     cuff: 3,        //   袖口の縁の太さ(px)。0/省略で縁なし
//     flare: 8        //   袖口の広がり(px)。広がり袖にしたいとき
//   },
//
//   wrap: {           // 包帯。false で無し
//     color: "#e8e0c8",
//     stripe: "#a89a78",
//     from: 0.08,     //   巻き始め 0〜1
//     to: 0.92,       //   巻き終わり 0〜1
//     count: 4        //   巻き目の数
//   },
//
//   band: {           // 腕甲・ブレーサー。false で無し
//     color: "#8a93a8",
//     from: 0.2,      //   開始位置 0〜1
//     to: 0.85,       //   終了位置 0〜1
//     pad: 2.5,       //   腕より太くする量(px)
//     rivet: "#fc3"   //   鋲の色。省略で鋲なし
//   }
// }
//
// 肘当て(body.elbowGuard):
//
//   elbowGuard: true
//   elbowGuard: { color: "#8a93a8", r: 6, spike: true }
//
//   r:     大きさ(px)。省略時は腕の太さに合わせる
//   spike: true または長さ(px)で、肘の外側にトゲが付く
//
// 例) 前腕だけ極太で金属の腕甲、上腕は細くて半袖
//
//   body: {
//     upperArm: { length: 25, width: 8, sleeve: { cover: 0.6, color: "#2a8", cuff: 3, trim: "#fc3" } },
//     lowerArm: { length: 27, width: 18, band: { color: "#c93", from: 0.2, to: 0.9, rivet: "#fff" } }
//   }
//
// 例) テンプレートだけ指定
//
//   body: { armType: "mageSleeve" }
//
// 例) テンプレートの袖の色だけ変える
//
//   body: { armType: "longSleeve", upperArm: { sleeve: { color: "#e9a" } } }



// ============================================================
// hair
// ============================================================
//
// 名前で指定(従来どおり)
//
//   hair: "raiki"
//
//   使用可能:
//     raiki
//     shino
//     blade
//     berserk
//
// 設定で指定(ロングヘアなど)
//
//   hair: { type: "long", color: "#5a3320", length: 0.75 }
//
// 複数を重ねて指定(配列。後ろに書いたものほど手前に描かれる)
//
//   hair: [
//     { type: "long",  color: "#5a3320", length: 0.75 },   // 後ろ髪
//     { type: "bangs", color: "#5a3320", sideburn: 0.7 }   // 前髪+もみあげ
//   ]
//
//   hair: ["shino", { type: "ahoge" }]   // 名前指定と混ぜてもよい
//
// type 一覧:
//   long        ロングヘア(結ばない)
//   ponytail    ポニーテール
//   twinTails   ツインテール
//   sideTail    サイドテール(頭の片側で1つに結ぶ。結び目に花飾り)
//   bun         お団子
//   bangs       前髪(センター分け / 横分け / ぱっつん)+もみあげ
//   sideburns   もみあげだけ(他の髪型に足す用)
//   ahoge       アホ毛
//
// 共通:
//   座標の x, y は頭の半径に対する割合。(0,0)=頭の中心、+x=顔の向き、-y=上
//   cap: false にすると、頭頂の髪のベース(帽子型)を描かない。
//   ※ 描画順は「後頭部の髪 → もみあげ → 耳」で、bangs を使っても使わなくても同じ。
//   back: 0〜1  頭頂の髪のベース(cap)を後頭部のどこまで伸ばすか。省略時1=うなじ側まで髪で覆う(耳は髪の上に描く)。
//        0 にすると従来どおり耳の高さで切れる。(long / ponytail / twinTails / bun で有効)
//        別の髪と重ねるときに使う(省略時は描く)
//   髪は走ったり動いたりすると毛先がなびく (物理で動く。下の「揺れ物(なびき)」を参照)
//     long / ponytail / twinTails / 側髪 / アホ毛 が動く。背中・頭に当たると止まり、体と重ならない
//     頭が背面寄り(向き -1.5 以下)のときは、後ろ髪(long / ponytail / twinTails)は最前面(体・腕・頭より手前)に描かれる
//   名前指定の髪(raiki / shino / blade / berserk)は動かない(berserk のトゲ髪だけ毛先がしなる)
//   アホ毛・もみあげ・側髪は、毛先だけでなく途中も一緒に動き、根元から傾くようにしなる
//
// ------------------------------------------------------------
// long (ロングヘア)
// ------------------------------------------------------------
//
// {
//   type: "long",
//
//   color: "#3a2a1a",
//
//   length: 0.7,     // 長さ  0=あご下 / 0.5=背中 / 1=腰  (1以上も可)
//
//   volume: 4,       // 髪の量(px)。大きいほど、真横では厚く・正面と背面では幅が広くなる
//                    //   ※ 髪の束と後頭部はひとつの形として描く(頭との間に線は出ない)。真横では背中に沿って垂れる
//
//   wave: 0.4,       // 波打ち 0〜1
//
//   tip: "point",    // 毛先の形: "point"(とがる) / "round"(丸い) / "flat"(ぱっつん)
//
//   maxBend: 0.42,   // ┐ 揺れの制限(省略可。省略時は全体の値)。このパーツだけ揺れ方を変えたいときに書く
//   maxRoot: 1.3,    // │   maxBend=節と節の間で曲がれる角度 / maxRoot=根元が静止時の向きから回れる角度(ラジアン)
//   reach: 0.7,      // │   reach=静止時の位置から離れられる距離(長さに対する割合)
//   maxV: 5,         // ┘   maxV=1フレームに動ける距離(px)   ※詳しくは下の「揺れ物(なびき)」
//   rootFlex: 0.6,   //     根元のやわらかさ 0〜1 (省略時は全体の値)。大きいほど根元から全体が振れる
// }
//
// ------------------------------------------------------------
// bangs (前髪 / センター分け / もみあげ)
// ------------------------------------------------------------
//
// {
//   type: "bangs",
//
//   style: "center",       // "center"=センター分け / "side"=横分け / "straight"=ぱっつん / "seeThrough"=シースルーぱっつん
//                          //   seeThrough: 短いぱっつんの下に、すき間から額が見える細い毛束が並ぶ(カルタ)。
//                          //     length(毛先の低さ。省略 0.6) / drop(毛束の長さ。省略 0.38) / count(毛束の数。省略 9) /
//                          //     width(毛束の太さの倍率) / spread(並ぶ幅の倍率)。側髪(sideburn)は straight と同じ
//
//   color: "#4a2c14",
//
//   part: 0,              // 分けた髪の角度 -1〜1 (省略0)
//                          //   center: 顔の真ん中の分け目をはさんで、左右の髪を同じ角度だけ開く/閉じる(左右対称)
//                          //           +1 で partAngle 度開く(額が広く、もみあげ・耳が後ろへ) / -1 で閉じる(前髪が顔を覆う)
//                          //           髪の生え際・側髪(もみあげ)・耳が一緒に回る
//                          //   side:   分け目の線の前後位置(+で顔側、-で後頭部側)
//
//   partAngle: 30,        // center の part=±1 で回す角度(度)。大きいほど part の効きが強い
//
//   partY: 0,             // 生え際の上下 -1〜1(+で生え際が下がり額が狭く、-で上がり額が広い)
//                          //   生え際の始点とカーブが一緒に変わる。省略時: center=0 / side=0.6
//
//   partColor: "#fff",    // 分け目の線の色。省略時は髪色に合わせて自動(暗い髪なら明るく)
//                          //   ※ straight は分け目なし
//
//   length: 0.1,           // 生え際の低さ 0〜1 (1で目に届く)。省略時: center/side=0.1 / straight=0.5
//
//   sideburn: 1.45,        // 側髪(耳の前に垂れる髪)の長さ。0で無し
//                          //   center/side: 1.45 で胸元まで垂れる(省略時) / 0.6 ならあご下くらい
//                          //   straight: 頭の半径に対する割合(省略時 0.6)
