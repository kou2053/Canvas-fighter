// ============================================================
// 影(アニメ塗りのセル影)   (drawing.js の SHADE)
// ============================================================
//
// キャラの絵に、境目のはっきりした影を自動で重ねる(光は「キャラの前の上」から当たる)。
//   腕・脚   … 節ごとに光と反対側の約3割      胴体 … 背中側(胸の飾り・服の上にも重なる)
//   頭       … あご・後頭部の三日月形          首   … 頭の下に落ちる影
//   鼻       … 鼻の下・奥側に落ちる影。nose: 'none' のアニメ顔のキャラは、鼻の位置に小さな影だけ描く(鼻の影で鼻を表す)
//   スカート・ローブ … すその下の脚に落ちる影(脚の形の中だけ)
// 影は「乗算」で重ねるので、元の色の色味を残して暗くなる。服・体は少し紫がかった影、肌は赤みのある影。
//   SHADE = { on: true, color: '#b8a2c0', deep: '#9a7fa6', skin: '#eab4a2', skinDeep: '#d6917f', width: 0.36 }
//     on=影を描くか / color=ふつうの影 / deep=濃い影(すその下など) / skin・skinDeep=肌の影 / width=腕・脚の影の幅(太さに対する割合)
//   色を濃くすると影が強くなる(白 #fff に近いほど薄い)。設定の画質が「低」のときは描かない(軽くするため)。
//   攻撃を受けて白く光っている間は描かない。

// ============================================================
// 顔・頭の形(イラスト風)   (drawing.js の HEAD_SHAPE / FACE_CURVE / drawing_template.js の EYE_ILLUST)
// ============================================================
//
// 頭の形 … 丸い頭蓋の下に、細くなるあごととがったあご先を付けた立体。頭の向き(姿勢配列13番目)で回してから投影するので、
//           真横 = あご先が前下に出た横顔 / 斜め = あごの線が片側に寄る / 正面 = 卵形の輪郭 / 背面 = 後頭部からうなじ
//   HEAD_SHAPE.on = false で以前の丸い頭。HEAD_SHAPE.chin / chinW / jaw / nape で形そのものを変えられる(頭の半径=1)
//   キャラごと(drawing_character.js の各キャラ)に、顔の形のテンプレートを名前で選ぶ (drawing.js の FACE_TEMPLATES):
//     headShape: 'shonen'   少年(少し骨太で、あご先は丸め)            … ライキ
//                'square'   いかつい四角いあご                       … ガルド
//                'cool'     頬がこけた鋭いあご                       … シノ
//                'wild'     張ったエラと広いあご                     … バーサク
//                'elegant'  大人っぽい細面(長めのとがったあご)       … ツキハ
//                'heroine'  細いあご先・ふっくらした頬               … リナ
//                'standard' ふつう / 'round' 丸顔(子どもっぽい)
//                'animeGirl'  アニメの女の子(丸い頬から小さく短いあご先へすぼまる)     … リナ
//                'illustGirl' イラストの女の子(すっきりした細いV字・少しとがったあご先) … ツキハ
//                (どちらも目より下を短くして、頭を大きく見せる。額は forehead: 0.94 で縦にまっすぐ(ほぼ直角))
//     headShape の forehead … 額の前の位置(頭の半径=1。省略で丸い頭)。書くと真横から見た額が縦にまっすぐな線になり、
//                上は頭頂の丸みへ、下は鼻の付け根へなめらかにつながる。小さいほど額が内側。
//                まっすぐにする範囲は drawing.js の FOREHEAD_V = { from(下端), to(上端), top(頭頂の丸みに戻る高さ), root(鼻の付け根で戻る高さ) }
//     headShape: { type: 'heroine', chin: 1.1 } … テンプレートの一部だけ変える
//     headShape: { jaw: 1.15, chin: 0.9, chinW: 1.4, cheek: 1 } … 直接書く(あごの幅 / あご先の長さ / あご先の幅 / 頬のふくらみ。倍率)
//     headShape: { chinPos: [0.5, -0.98], jawLine: [[前, 左右, 上下], ...4点] } … あご先の位置とあごの線を直接決める(頭の半径=1。animeGirl / illustGirl の書き方)
//       skull=頭蓋の丸みが続く下端の高さ(省略 -0.3。高いほど頬から下が早くすぼまる) / napeW=後頭部の下側の左右の幅(小さいほど正面のあごの横がすっきり)
//     headShape: false … そのキャラだけ丸い頭
//   FACE_TEMPLATES に新しい名前を足せば、ほかのキャラでも使える
//   後ろ髪・鉢巻の垂れが頭の後ろに隠れる範囲も、この形に合わせてある
//
// 目 … まつ毛の太い上まぶた(目尻のはね) / 細い下まぶた / 上から下へ明るくなる瞳 / 瞳孔 / ハイライト2つ / 白目に落ちるまぶたの影
//   EYE_ILLUST.on = false で以前の丸い目。EYE_ILLUST.types で目の種類ごとに調整:
//     purple / blue / cyan / anime  (normal / black / red = ライキ・ガルド・バーサクの目と、sharp / closed / shinosClosed / golem は元の目のまま)
//     iris=瞳の色(キャラの eyes.color が優先) / w, h=白目の横・縦 / irisW=瞳の横 / lash=上まぶたの太さ / wing=目尻のはね(true/false)
//
// 向きを変えたときの目・眉 … 頭の丸みに沿って貼る。横を細い短冊に分けて、その場所の顔の面がこちらを向いている分だけ幅を変える。
//   斜めでは奥の目が目尻ほど細く(丸みの向こうへ回り込む)、手前の目は目尻側が少し広い。正面では以前と同じ。
//   FACE_CURVE.strips = 短冊の数(0 で以前の平らな貼り方)。画質「低」では平らな貼り方
//
// 鼻と顔の輪郭 … 鼻を顔とひとつの形にして、外側にだけ輪郭を引く(鼻と顔の間に線が出ない)。輪郭は鼻筋→鼻先→鼻の下へなめらかにふくらむ
//   形は drawing.js の NOSE_PROFILE(normal / small / long / round / girl)。FACE_ILLUST.noseMerge = false で以前の別々の鼻
//   girl … イラストの女の子の鼻。鼻先の突き出しが小さく、鼻筋は額からなだらかに続く(リナ・ツキハ)。鼻の下に短い線も入れられる。
//          NOSE_PROFILE の smooth: true … 鼻筋を額の丸みの接線に沿って出し(角度が広い)、鼻の下は顔の中へなめらかにもどす(top: 鼻筋の始まりの高さ。小さい(上)ほど鼻筋が長くなだらかで、大きい(下)ほど鼻の上の角度が狭く、鼻がはっきり出る)
//          線は真横では鼻の下側に沿い、正面では横向きの短い線になる。長さ・下がり・太さは NOSE_UNDER_LINE.girl = { line, len, drop, w }
//          (いまは line: false で線を描かず、鼻先の小さなふくらみと小さな影だけ。true で線を描く)
//          (鼻を顔と一体にしないとき(noseMerge = false)は small の形で代用)
// 鼻・口(向きを変えたとき) … 正面寄りでは鼻を輪郭で囲まず、鼻の下の線と影だけで描く(drawing.js の FACE_ILLUST.nose = false で以前の菱形と太い口の線)。
//   口は正面でも広げすぎない(FACE_ILLUST.mouthWiden。以前は 0.9)。顔のペイント・傷は顔の形からはみ出さない
//
// 顔を覆う布(マスク) … faceMask: { color, nose, side, end, endY }
//   頭に巻いた1枚の布として立体で持ち、上端の線を頭の向きで回して描く(シノの口元の布)。
//   nose=鼻の所の上端の高さ(省略 -0.08) / side=真横の所の上端(省略 -0.55) / end=布の端の方位角(度。90=耳の下, 省略 125) / endY=端の高さ(省略 -0.85)
//   ※ 以前の faceCover(関数で真横の形を描く)も使えるが、斜め・正面では真横の形をずらして重ねるだけなので、布には faceMask を使う

// ============================================================
// 髪(イラスト風)   (drawing_template.js の HAIR_TIPS / drawing.js の HAIR_SHADE)
// ============================================================
//
// 毛束 … センター分けの前髪(bangs。ツキハ・リナ)は、分け目から左右へ流れる髪にする:
//         分け目から外・下へ生え際と並んで流れ、下の方で生え際に合流する流れの線(2本ずつ) + こめかみ・頬の方へとがって伸びる毛先。
//         側髪の先は2本に分かれてとがり、ロングヘアの毛先は3本、ツインテール・ポニーテールの毛先は2本の毛束に分かれる。
//   HAIR_TIPS = { on, depth(毛先の長さ), width(毛先の毛束の太さ), line(縁取り・流れの線の太さ), lowest(前髪の毛束を付ける縁の下限の高さ) }
//   キャラごと: hair の各項目に tips: 0〜2(毛束の長さの倍率) / tips: false(付けない) / shade: '#色'(髪の影の色。乗算)
//               ロングヘアは tip: 'split'(3本・省略時) / 'split2'(2本) / 'point'(1本にとがる) / 'round' / 'flat'
//   HAIR_TIPS.on = false で以前の形
