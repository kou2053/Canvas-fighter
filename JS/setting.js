// ============================================================
// 飛び道具の見た目・軌道  (character.js の projectile / プリセットと軌道の種類は projectile.js)
// ============================================================
//
// 飛び道具は「見た目(look)」と「軌道(path)」を選んで作る。見た目は技のエフェクトと同じく部品の組み合わせ。
//
// 書き方 (character.js):
//   projectile: { speed: 3.5, damage: 7, radius: 16, life: 200, look: 'darkOrb', path: 'straight' },
//   projectile: { ..., look: { preset: 'fireball', color: '#4cf', color2: '#dff' } },   // プリセットの色・大きさを変える
//   projectile: { ..., path: { type: 'wave', amp: 30, period: 50 } },                   // 軌道の数値を変える
//   projectile: { ..., path: { type: 'straight', angle: -20 } },                        // 斜め上へ撃つ
//
// 技ごとに変える: 技(s やコマンド技)に projectile: { ... } を書くと、その技だけキャラの projectile を上書きする
//   c3: { name: '空中苦無', command: '↓↘→+A', air: true, ..., projectile: { path: { type: 'straight', angle: 35 } } }  // 斜め下へ
//   c4: { name: '落石', command: '↓↙←+A', ..., projectile: { look: 'stone', path: 'arc', damage: 12 } }
//
// 性能の項目:
//   speed(速さ) / damage(威力) / radius(当たり判定の半径) / life(消えるまでのF) / count(一度に撃つ数) / spread(ばらけ方)
//   knockX / knockY / hitstun(当たったときの吹き飛び・硬直。省略時 4 / -4 / 22)
//
// 見た目(look)の項目:
//   preset   … 元にするプリセット(下の一覧)
//   color / color2 … 色(書かないとキャラのスキンの色)
//   size     … 絵の大きさ(radius に対する倍率。当たり判定は変わらない)
//   body     … 弾の絵の部品の一覧(下)。上から順に重ねる
//   spin     … 回る速さ(rad/F) / face: 'velocity' … 飛ぶ向きに絵を傾ける / pulse … 大きさのゆらぎ / glow … 光のにじみ(0 で無し)
//   trail    … 弾の後ろに残る物(下の「軌跡」。一覧で何個でも)
//   spawn / hit / vanish / reflect … 撃った瞬間 / 当たった瞬間 / 消えたとき / 跳ね返されたとき のエフェクト
//                                    中身は「技のエフェクト」の部品と同じ(slash / ring / burst / flame / star / heart / particles / shake ...)
//
// 弾の絵の部品 (body):  type と size color color2 alpha add(光る重ね方) x y spin
//   orb(光の玉) / ring(輪 width) / star(星 points inner) / crescent(三日月 thick) / blade(剣気の刃) / kunai(苦無) / arrow(矢) /
//   shuriken(手裏剣) / rock(岩) / bolt(雷の玉 count) / flame(炎のかたまり) / heart(ハート) / shard(氷のかけら) / wave(地面を走る波) /
//   petal(花びら) / sun(太陽 points)
//
// 軌跡 (trail):  type と color color2 rate(1Fに出す量) life(残るF) size
//   particles(粒 spread gravity) / sparkle(きらきら) / fire(炎の尾 rise smoke) / smoke(煙) / ghost(残像 count gap) / line(光の帯 length width)
//
// 見た目のプリセット (PROJECTILE_LOOKS):
//   basic(今までの玉) / fireball(火の玉・ライキ) / pressure(気弾・ガルド) / kunai(苦無・シノ) / bolt(雷の玉) /
//   swordWave(剣気) / stone(岩・ゴーレム) / breath(炎の息) / bloodWave(血風刃・バーサク) / darkOrb(闇の弾・リリス) /
//   star(星) / ice(氷) / shuriken(手裏剣) / arrow(矢) / heart(ハート) / shockwave(地面を走る衝撃波。path: 'ground' と使う) /
//   sunRay(光の矢・アサカ) / sunPetal(光の花びら・アサカ)
//   windBlade / tornado(ハヤテ) / iceLance / frostWave(セツカ) / seed / leafBlade(シゲル) / rocketFist / missile(ギア) / card / dice(カルタ)
//   軌道 seed(落ちると罠の芽になる) / rise(止まって浮き上がる)。弾に hits / hitEvery を書くと何回も当たる
//   プリセットは projectile.js の PROJECTILE_LOOKS に同じ書き方で足せる
//
// 軌道 (path):  すべてに angle(撃つ角度。度。マイナスで上向き) と from: { x, y }(弾の出る場所。足元から) が使える
//   straight  … まっすぐ(今まで通り)
//   wave      … 上下に波打つ          amp(波の高さ 22) period(1往復のF 44)
//   arc       … 放物線(地面で消える)   up(最初の上向きの速さ 7) gravity(重さ 0.25) bounce(跳ねる回数 0) bounceMul(跳ねる強さ 0.6)
//   ground    … 地面を這う(しゃがんでも当たる)
//   accel     … だんだん速くなる       start(最初の速さの倍率 0.3) accel(1Fに増える速さ 0.4。最大 speed)
//   stop      … 遅くなって止まる(設置)  decel(1Fごとに速さに掛ける数 0.94)
//   homing    … 相手を追いかける       turn(1Fに曲がる角度 0.05) delay(追い始めるまでのF 10)
//   boomerang … 前に飛んで戻ってくる    back(戻る力 0.35)。持ち主の所まで戻ると消える
//   ※ ジャストガードで跳ね返された弾は、軌道が straight に変わって撃った側へ飛ぶ
//   ※ CPU は軌道どおりに弾の動きを予測して、ジャンプ・ジャストガードで対処する
//   ※ 軌道を変えると強さも変わる(ground はしゃがんで避けられない、homing は当たりやすい など)。変えたら CPU 対戦で確かめる