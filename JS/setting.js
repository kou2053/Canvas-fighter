// ============================================================
// 揺れ物(なびき)  … 髪・鉢巻・リボン・マフラーなどの物理
// ============================================================
//
// 「点をつないだひも」として毎フレーム計算し、キャラの動き(走る・跳ぶ・攻撃・振り向き・顔の向き)に遅れてなびく。
//
// 物理で動くもの:
//   headgear … headband の tails / ribbon の垂れ
//   hair     … long / ponytail / twinTails / 側髪(bangs の sideburn・sideburns) / ahoge
//              トゲ髪(berserk)は毛先がしなるだけ。raiki の髪は動かない
//   clothes  … scarf の端 / cape・robe(すそ)・skirt・loincloth のすそ(上の「服の揺れ(物理)」)
//   シノ      … 首巻き(extraCollar) / 帯(waist)  ※ drawing_character.js に例として書いてある
//
// 動きの決まり:
//   ・背中より前には入らない(背中で止まる) / 頭を突き抜けない / 地面より下に行かない
//   ・振り向き(左右反転)では一緒に反転する。ヒットストップ中は止まる
//   ・頭が回ったとき(顔のX軸の向きの変化)は、結び目と一緒に垂れも運ぶ。正面・背面に近いほど真下へ垂れる
//   ・はためきの強さは体が空気を切る速さで決まる(止まっていればほぼ動かない)
//   ・変な形にならないよう、曲がり・距離・速さに上限がある(下の PHYS_MAX_BEND など)
//
// 全体の調整 (drawing.js の「揺れ物の物理」):
//   PHYS_GRAVITY       0.25  重力(px/フレーム²)。大きいほど重く垂れる
//   PHYS_SMOOTH        0.4   見た目のなめらかさ。小さいほど形の変化をならす(ゆったり。揺れの幅は少し減る)
//   PHYS_TIME          0.8   揺れの時間の進み方(1=実時間)。小さいほどゆっくり揺れる。下げすぎると体の動きに置いていかれる
//   PHYS_DAMP          1     空気抵抗の倍率。大きいほど早く止まる
//   PHYS_FLUTTER_SPEED 0.42  布のはためきの速さ
//   PHYS_MAX_BEND      0.42  節と節の間で曲がれる角度(ラジアン。0.42 ≒ 24°)。大きいほど大きくしなる
//   PHYS_MAX_ROOT      1.3   根元の節が静止時の向きから回れる角度(≒75°)
//   PHYS_REACH         0.7   静止時の位置から離れられる距離(根元からの長さに対する割合)。大きいほど遠くまでなびく
//   PHYS_MAX_SPEED     3     1フレームに動ける距離(px)
//   PHYS_ROOT_FLEX     0.6   根元のやわらかさ(0〜1)。大きいほど先だけでなく根元から全体が振れる。0 で以前の動き(先だけがしなる)
//                            ・根元の硬さを下げ、根元の節が体の動きにそのまま付いていかず遅れて振れるようにする
//                            ・やわらかくした分の垂れは自動で打ち消すので、止まっているときの形は変わらない
//                            ・振れられる範囲(reach)もこの値に合わせて広がる(最大1.5倍)
//   ※ PHYS_MAX_BEND / PHYS_MAX_ROOT / PHYS_REACH / PHYS_MAX_SPEED / PHYS_ROOT_FLEX は、パーツごとに maxBend / maxRoot / reach / maxV / rootFlex で変えられる
//      書ける場所: headgear の headband / ribbon、hair の long / ponytail / twinTails、clothes の scarf、ctx.strand の設定
//      例) headgear: [{ type: 'headband', tails: 2, maxBend: 0.25, reach: 0.5 }]   // 鉢巻の垂れを硬め・控えめに
//      例) hair: { type: 'ponytail', rootFlex: 1 }   // ポニーテールを根元から大きく振る / rootFlex: 0 で先だけしなる
//
// キャラ専用の描画(torso / waist / extraCollar / back など)で揺れ物を作る:
//
//   const pts = ctx.strand('名前', 根元[x, y], {
//     len: 30,             // 長さ(px)
//     dir: [-20, 10],      // 静止時の向き(+x=顔の向き, +y=下)
//     n: 5,                // 節の数(多いほどなめらか。省略5)
//     curve: 0,            // 節ごとの曲がり(ラジアン)
//     stiff: [0.2, 0.01],  // 形を保つ強さ [根元, 先] 0〜1。根元ほど硬く、先ほどやわらかい
//     damp: 0.08,          // 空気抵抗
//     grav: 1,             // 重さの倍率
//     flutter: 0,          // はためき(布なら 0.8〜1.4)
//     seed: 0,             // はためきのずらし(何本か並べるときに変える)
//     collide: 'back',     // 'back'=背中で止まる / 'none'=当たり無し
//     r: 2,                // 太さ(当たりの余白px)
//     head: false,         // true で頭も突き抜けない
//     anchor: null,        // 頭に付ける物は [ctx.hcx, ctx.hcy] を渡す(頭が回ると一緒に運ばれ、背面・正面での当たりも頭の向きに合う)
//
//     // 揺れの制限 (省略時は全体の値 PHYS_MAX_BEND / PHYS_MAX_ROOT / PHYS_REACH / PHYS_MAX_SPEED)
//     maxBend: 0.42,       // 節と節の間で曲がれる角度(ラジアン)。小さいほどまっすぐ硬く、大きいほどしなる。0.42 ≒ 24°
//     maxRoot: 1.3,        // 根元の節が静止時の向き(dir)から回れる角度(ラジアン)。小さいほど根元が向きを保つ。1.3 ≒ 75°
//     reach: 0.7,          // 静止時の位置から離れられる距離。根元からの長さに対する割合(先ほど遠くまで動ける)。
//                          //   小さいほど静止時の形の近くで揺れ、大きいほど大きく流れる
//     maxV: 5,             // 1フレームに動ける距離(px)。小さいほど急な動きが抑えられる
//     rootFlex: 0.6        // 根元のやわらかさ 0〜1。大きいほど根元から全体が振れる(0=先だけがしなる)
//   });
//   ※ 制限に当たったときは、はね返らずに境目に沿って止まる
//   // pts は根元から先までの点の列(描画座標)。描き方は自由。用意してある描き方:
//   strandRibbon(ctx, pts, 根元の太さ, 先の太さ, 色, 縁取り(true/false))   … 帯・ひも
//   ctx.g.fillStyle = 色; strandShape(ctx.g, pts, 根元の半幅, 先の半幅, 'point' | 'round' | 'flat'); ctx.g.fill(); ctx.ol(2);   … 毛束
//
//   const [dx, dy] = ctx.jiggle('名前', 付け根[x, y], { k: 0.14, damp: 0.2, max: 5 });
//   // バネで遅れて付いてくるずれ(px)。トゲ髪の先・飾りの先などに足すと、頭の動きに遅れてしなる
//
//   ※ '名前' はキャラの中で重ならないようにする(同じ名前は同じひもとして続きから計算される)
//   ※ 例: シノの extraCollar(首巻き) / waist(帯) … drawing_character.js


// ============================================================
// 腕・脚の形 (drawing.js の LIMB_SHAPES)
// ============================================================
//
// 腕・脚は「根元(肩・股関節) → 関節(肘・ひざ) → 先(手首・足首)」を、太さの変わるなめらかな形で描く。
//   ・関節に丸(ボルトのような円)は描かない。上と下の形は輪郭をつなげて1つの形にするので、継ぎ目の線が出ない
//   ・根元(肩・股関節)の輪郭は細くして、体から生えているように見せる
//   ・手は前腕の向きに握ったこぶし(親指つき)。手首は細くくびれて手につながる
//   ・袖・包帯・腕甲・腕輪・ズボンのすそ・すね当て・ブーツなども、腕・脚の形(くびれ)に沿って描く
//   ・太さの基準は body の upperArm / lowerArm の width と legWidth(当たり判定は今までどおり、その太さのまま)
//
// LIMB_SHAPES[種類] = {
//   upper: [[位置, 倍率], ...],   // 上の節(上腕・太もも)の太さ。位置 0=根元 〜 1=関節、倍率 1=width のまま
//   lower: [[位置, 倍率], ...],   // 下の節(前腕・すね)の太さ。位置 0=関節 〜 1=手首・足首
//   offL:  [[位置, 量], ...]      // 下の節を後ろ側へふくらませる量(ふくらはぎ)。null で無し
// }
//   arm   … 腕(人)   上腕: 肩 1.02 → 力こぶ 1.06 → 肘 0.8 / 前腕: 肘 0.82 → 筋肉 1.0 → 手首 0.62
//   leg   … 脚(人)   太もも: 付け根 1.06 → ひざ 0.82 / すね: ひざ 0.84 → ふくらはぎ 1.0 → 足首 0.62
//   block … まっすぐ(body.limbShape: "block")
//   数字を変えると、全キャラの腕・脚の形が変わる(例: 手首をもっと細く → arm.lower の最後を 0.5 に)


