// ============================================================
// 向き (X軸の向き): 頭 と 体の7部位を別々に変えられる
// ============================================================
//
// 向きの値:  0=真横  1=少し正面向き  2=まあまあ正面向き  3=正面向き
//           -1=少し背面  -2=まあまあ背面  -3=背面       (小数は回っている途中の見た目)
// 向きを持つ部位: 頭 / 胴 / 右上腕 / 右前腕 / 左上腕 / 左前腕 / 右足 / 左足
//   何も指定しないと 頭=0 / 体=1 (従来の見た目)。指定のしかたは character.js 冒頭の【向き】を参照。
//
// 向きごとの絵は CHARACTER_DRAWS の設定から自動で描かれる(キャラごとに別の絵を描く必要はない)。
//   頭 … eyes / brows / nose / mouth / showEars / hair / headgear / faceDeco / faceCover を向きに合わせて描き直す
//        正面側: 奥側の目が見えてくる・鼻や口が中心へ寄る・髪の生え際が額を横切る・ポニーテールが後ろへ隠れる など
//        背面側: 顔が隠れて髪が頭を覆い、後ろ髪(ポニーテール・ロングなど)が見ている側に垂れる。鉢巻の結び目も見える
//               向き -1.5 以下では 後ろ髪 → 頭の装飾(headgear の front) の順に最後に描く(体・腕・頭より手前)
//        ※ headgear の layer:'back' は「奥側の物」として扱う(horn など)
//   胴 … 胴体の幅(背面も正面と同じ幅) / 服(cape・scarf・loincloth・skirt・robe)。
//        背面では胸側の装飾(torso・バックル)が隠れ、背中の装飾(back)・マントが胴の手前に来る
//   腕 … 上腕・前腕それぞれが「見ている人の方へどれだけ向いているか」を表す。付け根(肩)の位置は変わらない(肩は胴の向きで決まる)。
//        正面側(2〜3): その節が手前へ傾くので、前後方向の長さが縮んで見え、付け根から先へだんだん大きく見える
//        背面側(0〜-3): 奥へ傾くので、同じように縮み、先へだんだん小さく見える
//        1 以下〜0 は真横の絵のまま(標準)。±3 で真正面・真後ろを指す(前後方向の長さが無くなる)
//        前腕の向きで手(こぶし)の見え方も変わる: 手前を向くと拳の正面(指)が見えて大きく、奥を向くと小さく前腕の陰に隠れる
//   足 … 脚(太もも・すね)と靴が同じ向きに回る。付け根(股関節)の位置は変わらない
//        正面・背面へ向くほど、ひざの曲がり(前後の幅)が縮んで見え、靴は前後に短く・左右の幅が見えてくる
//        正面ではつま先、背面ではかかとが見える
//   ※ 縮み・大きさの変化は当たり判定(fighterHitParts)にも同じように入る(大きさの変化は見た目だけ)
//   torso / waist / shoulder などキャラ専用の描画は ctx.P(t, o) の座標なので、胴体の幅の変化にそのまま追従する
//
// キャラ専用の描画(torso / headCustom など)の中では次が使える:
//   ctx.headDir / ctx.bodyDir(胴) / ctx.partDir(部位ごと: rUpperArm, rForeArm, lUpperArm, lForeArm, rLeg, lLeg)  … 今の向き(-3〜3)
//   ctx.hv   … 頭の見え方。hv.turned(真横以外か) / hv.back(背面側か) / hv.fv(顔の中心線が見える度合い) /
//              hv.cs, hv.sn(顔の向きの cos, sin) / hv.as(|sn|) / hv.X(F, R) / hv.S(F, R) / hv.Y(U)
//   ctx.G    … 体の見え方。G.sym(0=真横〜1=正面/背面) / G.fm, G.bm(胴の前側・背中側の幅の倍率) / G.shN, G.shF(右・左の肩) など
//   headCustom を使うキャラ(ゴーレムなど)は、真横以外のときの絵を ctx.hv を見て自分で描き分ける
//   faceCover(口元の布など)は、真横用の形を左右反転して近似する。斜めの線があると正面で X 字に見えるので、
//     その場合は faceCoverTurned(ctx) を書くと、真横以外ではそちらが使われる(ctx.hv を見て正面用の形を描く)
//
// 見た目の調整 (drawing.js):
//   HEAD_PHI / HEAD_PHI_BACK … 頭の向きごとの角度 [真横, 少し, まあまあ, 正面(背面)] (ラジアン)。負の向きは HEAD_PHI_BACK
//   BODY_DIR … 体(胴)の向きごとの形 [真横, 少し, まあまあ, 正面(背面)]
//              shN/shF=右・左の肩の開き, hipN/hipF=右・左の脚の付け根, front=胴の幅, sym=左右対称の度合い (toe は今は使わない)
//   limbTheta(d) … 腕・脚の向き d を回る角度にする(1以下〜0=0 / 3=真正面 / -3=真後ろ)
//   LIMB_PERSPECTIVE … 手前・奥へ出た分の大きさの変化(0.28 = 節1本ぶん手前へ出ると 1.28 倍)
//   当たり判定(fighterHitParts)も同じ BODY_DIR と部位ごとの向きを使うので、見た目と判定は常にそろう
//

