//
//   ・数値はその部位の「いちばん外側の輪郭」の太さ(px)。今の数値が以前と同じ見た目。0 で線なし
//   ・部位の中の細かい線(指の付け根・服の縁・鼻の小さい線など)も、同じ割合で太く/細くなる
