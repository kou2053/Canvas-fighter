//   ※ 口の線の太さは mouth.lineWidth、眉の太さは brows.thickness で別に決める(ここでは変わらない)
//   ※ キャラ専用の描画で ctx.ol(太さ) を使うと custom の割合がかかる。今の割合は olScale() / olScale('hand') などで取れる
