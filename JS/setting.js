// 陰影 … 髪を描いたあと、髪の形の内側だけに重ねる(どの髪型でもはみ出さない):
//   影(頭の上の髪の、光と反対側の三日月 + 垂れた髪の毛束の筋)
//   / 毛流れ(毛並みに沿った両端の細い線。センター分けのキャラは分け目から左右・後ろへ流れ、それ以外は頭頂から四方へ)
//   / ハイライト(天使の輪の高さで、毛流れに沿って光る細い筋。サラサラ感。頭の向きで回る)
//   HAIR_SHADE = { on, shadow(影の色・乗算), warm(金髪など明るい暖色の髪の影の色), lines(毛流れの線の本数), light(ハイライトの強さ 0〜1), flow(毛流れの濃さ 0〜1), ring(天使の輪の高さ), mid(画質「中」でも描くか) }
//   画質「高」「最高」だけで描く(重いため。HAIR_SHADE.mid = true で「中」でも描く)。攻撃を受けて白く光っている間は描かない
