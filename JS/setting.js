// ============================================================
// 技のエフェクト  (character.js の moves の effect / プリセットは effect.js の EFFECT_PRESETS)
// ============================================================
//
// エフェクトは「部品」を並べて作る。キャラの見た目と同じく、部品の種類と設定を組み合わせる。
// 出すタイミングは3つ:
//   start  … 技の出始め(溜め・構え)
//   attack … 攻撃の瞬間(当たり判定が出たとき。空振りでも出る)
//   hit    … 当たった瞬間(当たった場所に出る。ガードされたときは出ない)
//
// 書き方:
//   effect: 3                                     // 今まで通り(色の番号 0〜7 の決まった見た目)
//   effect: 'fire'                                // プリセットの名前だけ
//   effect: { preset: 'fire', color: '#4cf' }     // プリセットの色・大きさ・時間などを変える
//   effect: { preset: 'fire', hit: [ ... ] }      // プリセットの一部(hit だけ)を自分の部品に差し替える
//   effect: [ {部品}, {部品} ]                     // attack の部品だけ書く
//   effect: {                                     // 全部自分で作る
//     color: '#6f9',             // 全部品の色(部品ごとに書けばそちらが優先)
//     color2: '#fff',            // 2つめの色(弧の内側・光の中心・粒の一部など)
//     size: 1.2,                 // 全部品の大きさの倍率
//     duration: 12,              // 全部品の長さ(F)
//     blend: 'add',              // 'add' で光る重ね方(明るくなる)
//     strength: 1,               // 強さ(全部品)。大きいほど量・太さ・勢いが増える(下の「強さ」)
//     start:  [ ... ],
//     attack: [ ... ],
//     hit:    [ ... ],
//   }
//
// 部品の共通設定(すべて省略可):
//   {
//     type: 'slash',     // 部品の種類(下の一覧)
//     at: 'hitbox',      // 出す場所: hitbox=技の当たり判定の真ん中(attack・start の既定) / hit=当たった場所(hit の既定) /
//                        //           body=体の真ん中 / feet=足元 / front=体の少し前(手元) / head=頭の上 /
//                        //           base=技の当たり判定の手前の端(突きの光線 beam の出どころに使う) /
//                        //           ground=技の当たり判定の真ん中の真下の地面(空から降りる光の柱 pillar など)
//     x: 0, y: 0,        // 場所からのずれ(px)。x は前方向がプラス、y は下がプラス
//     r: 40,             // 大きさ(px)。省略すると技の当たり判定の大きさから自動で決まる
//     size: 1,           // 大きさの倍率
//     duration: 12,      // 出ている長さ(F)
//     delay: 0,          // 出るまで待つF(何個かを時間差で出すとき)
//     color: '#fff',     // 色
//     color2: '#fff',    // 2つめの色
//     width: 10,         // 線の太さ(px)
//     blend: 'add',      // 'add' で光る重ね方
//     follow: false,     // true でキャラに付いていく(溜めの光など)
//     strength: 1,       // 強さ。技全体の strength と掛け算(0 でその部品は出ない / 最大 5)
//   }
//
// 強さ(strength)で変わるもの … 1 が今の見た目。2 で「だいぶ派手」、3 で「とても派手」、0.5 で控えめ
//   flame     火の粉の量が増え(強さ倍)、炎が大きく高くなる
//   particles 粒の数が増え(強さ倍)、飛ぶ勢いと残る長さが増える
//   spark     稲妻の本数が増える(強さ2で2本、3で3本)
//   burst     放射線の数が増え、輪が太く大きくなる
//   lines     速度線の本数が増える
//   star      まわりに小さい星が増える(強さ2で1つ、3で2つ)
//   flash/orb 光が大きくなる
//   slash/cross/ring/wave/beam  線が太くなる
//   shake     揺れが強くなる(power × 強さ)
//   どの部品も、出ている時間が少し長くなる(強さ1につき +10%)
//
// 部品の種類(type)と、その部品だけの設定:
//   slash     斬撃の弧            angle(傾き -1=上向き 0=横 1=下向き 'auto'=技に合わせる・省略時) / span(弧の長さ。ラジアン 2.2)
//   cross     ×字の斬撃           width
//   ring      広がる輪            flat(true で地面の楕円) / grow(広がる量 1)
//   wave      地面を走る衝撃波     (足元に出すと良い at: 'feet') / grow
//   spark     稲妻                length(長さ) / count(折れ目の数 6)
//   flame     炎(火の粉で描く)     count(1Fに出す火の粉の量 4) / rise(昇る速さ 2.2) / buoyancy(上への加速 0.17) /
//                                 spread(横のばらつき 0.9) / push(前へ吹き出す速さ 0) / smoke(煙になる割合 0〜1、0.2) / life(火の粉が残るF 24)
//                                 炎は出ている間ずっと火の粉を出し、出どころはキャラに付いていく(follow。当たった瞬間の炎は付いていかない)。
//                                 出た火の粉はその場で昇り続けるので、炎を出しながら動くと炎の尾が後ろに伸びる
//                                 color=炎の色 / color2=芯の色(明るい色にする)  例) 青い炎 color: '#3af', color2: '#cff'
//                                 dir=炎の向き: 'up'(上・省略時) / 'down' / 'forward'(前) / 'back'(後ろ) / 数字=角度(度)
//                                   角度は 0=前 90=上 -90=下 180=後ろ 45=斜め前上。キャラが左を向くと自動で左右反転
//                                   rise / buoyancy / life は「その向きへ」の速さ・加速・長さになる
