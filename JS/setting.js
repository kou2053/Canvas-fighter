//   ・スカート: めくれすぎないよう、振れる角度と距離を小さめにしてある。短いスカートほど硬く、長いほどやわらかい
//   ・脚との当たり: スカート・ローブのすそ・腰布の前の端は脚より前、後ろの端は脚より後ろに来る。
//     脚を前に出す(蹴り・走り)とスカートの前が押されて広がり、脚がスカートを突き抜けない。脚の位置と向き(ひざの曲がり)に合わせて動く
//   服ごとに書ける項目(すべて省略可):
//   {
//     physics: false,       // 揺れなし(以前と同じ動き)
//     legs: false,          // 脚との当たりを使わない(脚の上にかぶさっても押されない)
//     overSkirt: false,     // (マントだけ) スカートの外側を通らない
//     fadeBy: 'wing',       // キャラの記憶 ctx.mem の値(0〜1)が大きくなるほど透けて消える。
//                           //   リリスのマントは fadeBy: 'wing'(夢幻蝶で羽が生えている間は消え、羽が消えると戻る)
//     stiff: [0.4, 0.1],    // 形を保つ強さ [根元, 先] 0〜1。大きいほど硬く、揺れが小さい
//     flutter: 0.6,         // はためきの強さ(0で無し)
//     weight: 1,            // 重さの倍率。大きいほど重く垂れる
//     maxRoot: 0.6,         // 根元が振れる角度(ラジアン)。スカートをもっとめくれにくくするなら小さく
//     reach: 0.4,           // 静止時の形から離れられる距離(長さに対する割合)
//     maxBend / maxV / rootFlex  // 下の「揺れ物(なびき)」と同じ
//   }
//   例) 重くて揺れにくいローブ   { type: 'robe', color: '#445', stiff: [0.6, 0.2], weight: 1.5 }
//   例) ひらひら大きくなびくマント { type: 'cape', color: '#a22', flutter: 1.6, reach: 1 }

// ============================================================
// 手首の角度・武器の位置・向き (character.js の姿勢配列)
// ============================================================
//
// 姿勢配列(poses / motions の w・s / hitPoses など)の並び:
//   [lean, 右肩, 右肘, 右手首, 左肩, 左肘, 左手首, 右腿, 右膝, 左腿, 左膝, 前後ずれ, 武器X, 武器Y, 武器角度, 頭, 胴, 部位6つ]
//   右手首・左手首 … こぶし(と持っている武器)の向き(rad)。0=前腕と同じ向き / + で前(親指の側)へ曲げる / - で後ろへ
//   武器X     … 手からの位置(px)。+ が前方向
//   武器Y     … 手からの位置(px)。+ が下、- が上
//   武器角度  … 持ち方(drawing_character.js の weaponGrip)からの差分(rad)。+ で武器の先が前方向へ傾く
//   武器X〜は省略時 0。前の12個(lean〜前後ずれ)だけの配列も使える。
//   ※ weapon(ctx, e, ux, uy) には、握る位置 e と、武器の向き (ux, uy) が渡される。
//   ※ 技の当たり判定(box)は武器の動きに連動しない。武器の先に判定を合わせたいときは box を調整する。
//
// ============================================================
// 当たり判定について (被弾側の判定)
// ============================================================
//   見た目と同じ大きさ(scale・着地や攻撃時のつぶれ)・脚の長さと太さ(thighLength / shinLength / legWidth / thighWidth / shinWidth)
